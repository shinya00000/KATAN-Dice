import { describe, expect, it } from 'vitest';
import { IR, katanDecrypt, katanEncrypt, katanEncryptTrace, type KatanVariant } from '../src/crypto/katan';

/** IR table copied verbatim (ONES→1, 0→0) from the designers' reference katan.c */
const IR_REFERENCE =
  '11111110001101010101111011001100101001000100011000111100001000010100000111110011111101010001010100110000110011101111101110100101011010011100110110001011101101111001011011010111001001001101000111000100111101000011101011000001011001000000110111000000010010';

/**
 * Independent oracle: a literal transliteration of katan64_encrypt() from katan.c
 * using BigInt registers instead of bit arrays (fa_2/fa_1/fa_0 spelled out).
 */
const oracleKatan64 = (key: bigint, plain: bigint): bigint => {
  const bit = (v: bigint, i: number): bigint => (v >> BigInt(i)) & 1n;
  const k: bigint[] = [];
  for (let i = 0; i < 80; i++) k.push(bit(key, i));
  for (let i = 80; i < 508; i++) k.push(k[i - 80]! ^ k[i - 61]! ^ k[i - 50]! ^ k[i - 13]!);
  let L2 = plain & ((1n << 39n) - 1n);
  let L1 = plain >> 39n;
  const ir = IR_REFERENCE.split('').map((c) => BigInt(c));
  for (let i = 0; i < 254; i++) {
    const a = (o: number): bigint =>
      bit(L1, 24 - o) ^ bit(L1, 15 - o) ^ (bit(L1, 20 - o) & bit(L1, 11 - o)) ^ (bit(L1, 9 - o) & ir[i]!) ^ k[2 * i]!;
    const b = (o: number): bigint =>
      bit(L2, 38 - o) ^ bit(L2, 25 - o) ^ (bit(L2, 33 - o) & bit(L2, 21 - o)) ^ (bit(L2, 14 - o) & bit(L2, 9 - o)) ^
      k[2 * i + 1]!;
    const fa2 = a(0), fa1 = a(1), fa0 = a(2);
    const fb2 = b(0), fb1 = b(1), fb0 = b(2);
    L1 = ((L1 << 3n) & ((1n << 25n) - 1n)) | (fb2 << 2n) | (fb1 << 1n) | fb0;
    L2 = ((L2 << 3n) & ((1n << 39n) - 1n)) | (fa2 << 2n) | (fa1 << 1n) | fa0;
  }
  return (L1 << 39n) | L2;
};

/** deterministic 64-bit generator for test inputs (splitmix64) */
const splitmix = (seed: bigint) => {
  let s = seed;
  return (): bigint => {
    s = (s + 0x9e3779b97f4a7c15n) & 0xffffffffffffffffn;
    let z = s;
    z = ((z ^ (z >> 30n)) * 0xbf58476d1ce4e5b9n) & 0xffffffffffffffffn;
    z = ((z ^ (z >> 27n)) * 0x94d049bb133111ebn) & 0xffffffffffffffffn;
    return z ^ (z >> 31n);
  };
};

describe('KATAN', () => {
  it('IR generated by the 8-bit LFSR equals the reference table', () => {
    expect(IR.join('')).toBe(IR_REFERENCE);
  });

  it('KATAN64 matches the literal transliteration of the reference code', () => {
    const rnd = splitmix(1n);
    const cases: [bigint, bigint][] = [
      [(1n << 80n) - 1n, 0n],
      [0n, (1n << 64n) - 1n],
    ];
    for (let i = 0; i < 40; i++) cases.push([(rnd() << 16n) ^ (rnd() & 0xffffn), rnd()]);
    for (const [key, plain] of cases) {
      expect(katanEncrypt(64, key, plain)).toBe(oracleKatan64(key, plain));
    }
  });

  it.each<KatanVariant>([32, 48, 64])('KATAN%i decrypt(encrypt(x)) = x', (variant) => {
    const rnd = splitmix(BigInt(variant));
    const mask = (1n << BigInt(variant)) - 1n;
    for (let i = 0; i < 30; i++) {
      const key = ((rnd() << 16n) ^ rnd()) & ((1n << 80n) - 1n);
      const plain = rnd() & mask;
      const c = katanEncrypt(variant, key, plain);
      expect(c).not.toBe(plain);
      expect(katanDecrypt(variant, key, c)).toBe(plain);
    }
  });

  it('trace has 255 snapshots and ends at the ciphertext', () => {
    const key = 0x0123456789abcdef0123n;
    const t = katanEncryptTrace(64, key, 42n);
    expect(t.snapshots).toHaveLength(255);
    const last = t.snapshots[254]!;
    expect((BigInt(last.l1) << 39n) | BigInt(last.l2)).toBe(t.ciphertext);
    expect(t.ciphertext).toBe(katanEncrypt(64, key, 42n));
  });

  it('rejects out-of-range inputs', () => {
    expect(() => katanEncrypt(64, 1n << 80n, 0n)).toThrow(RangeError);
    expect(() => katanEncrypt(32, 0n, 1n << 32n)).toThrow(RangeError);
  });
});

describe('KATAN regression values (format of test_values() in katan.c)', () => {
  // All values confirmed by compiling and running the designers' reference katan.c (test_values()).
  const ONES80 = (1n << 80n) - 1n;
  it.each<[KatanVariant, bigint, bigint, bigint]>([
    [32, ONES80, 0n, 0x7e1ff945n],
    [32, 0n, 0xffffffffn, 0x432e61dan],
    [48, ONES80, 0n, 0x4b7efcfb8659n],
    [48, 0n, 0xffffffffffffn, 0xa4bd196d0b85n],
    [64, ONES80, 0n, 0x21f2e99c0fab828an],
    [64, 0n, 0xffffffffffffffffn, 0xc956100dbeb64ba8n],
  ])('KATAN%i key=%s plain=%s', (v, key, plain, expected) => {
    expect(katanEncrypt(v, key, plain)).toBe(expected);
  });
});

describe('KATAN64 known answers with non-trivial keys (output of the reference katan.c)', () => {
  // key bit i = key[i], plain bit i = plain[i], cipher bit i = cipher[i] in katan64_encrypt()
  it.each<[bigint, bigint, bigint]>([
    [0xd093157a3807a48faa9dn, 0x2f90b72e996dccben, 0x84a619f84f94cb1fn],
    [0x8008a2d419334c4667ecn, 0x14bc574c2a2b4c72n, 0x4d22ba24632b273an],
    [0xa651b8fc5b1060708c05n, 0xf984db4ef14fde1bn, 0x9a2b115d6544f945n],
    [0xda0f2680d065cb73ece7n, 0x6a6e60fd5089adecn, 0x394b5583df3664b2n],
    [0xb13b8eba85b28df77747n, 0x380e8b5c685039cfn, 0xc5f0c94e61548b01n],
  ])('key=%s', (key, plain, cipher) => {
    expect(katanEncrypt(64, key, plain)).toBe(cipher);
    expect(katanDecrypt(64, key, cipher)).toBe(plain);
  });
});
